"""Generate sql/schema.sql from metadata/source_profile.json.

Run once after profiling. Commit the generated file.
Re-run if feature columns change.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

PROFILE = Path("metadata/source_profile.json")
OUT     = Path("sql/schema.sql")

AUDIT_COLS = {
    "ingest_run_id", "transform_run_id", "source_row_number",
    "source_row_key", "record_hash", "flag_conflicting_label",
    "is_malware", "class",
}

SQL_IDENT_OK = re.compile(r"^[a-z_][a-z0-9_]*$")


def q(name: str) -> str:
    """Quote a column name if it is not a safe bare identifier."""
    if SQL_IDENT_OK.match(name):
        return name
    return '"' + name.replace('"', '""') + '"'


def main() -> int:
    if not PROFILE.exists():
        print(f"ERROR: {PROFILE} not found. Run src/profile_source.py first.", file=sys.stderr)
        return 1

    profile = json.loads(PROFILE.read_text(encoding="utf-8"))
    all_cols = profile["column_names"]
    feature_cols = [c for c in all_cols if c not in AUDIT_COLS]

    lines: list[str] = []
    lines.append("-- =============================================================================")
    lines.append("-- Generated by scripts/generate_schema.py. Do not edit by hand.")
    lines.append(f"-- Source: {PROFILE}")
    lines.append(f"-- Feature columns: {len(feature_cols)}")
    lines.append("-- =============================================================================")
    lines.append("")
    lines.append("-- Rerun-safe curated table. Load path uses INSERT ... ON CONFLICT (source_row_key)")
    lines.append("-- DO NOTHING, so re-running the pipeline never duplicates logical records.")
    lines.append("CREATE TABLE IF NOT EXISTS curated_apps (")
    lines.append("    source_row_key          TEXT PRIMARY KEY,")
    lines.append("    source_row_number       INTEGER NOT NULL UNIQUE,")
    lines.append("    record_hash             TEXT NOT NULL,")
    lines.append("    ingest_run_id           TEXT NOT NULL,")
    lines.append("    transform_run_id        TEXT NOT NULL,")
    lines.append("    flag_conflicting_label  BOOLEAN NOT NULL,")
    lines.append("    is_malware              SMALLINT NOT NULL CHECK (is_malware IN (0, 1)),")

    for i, col in enumerate(feature_cols):
        comma = "," if i < len(feature_cols) - 1 else ""
        lines.append(f"    {q(col):<60s} SMALLINT NOT NULL CHECK ({q(col)} IN (0, 1)){comma}")

    lines.append(");")
    lines.append("")
    lines.append("CREATE INDEX IF NOT EXISTS idx_curated_apps_is_malware    ON curated_apps (is_malware);")
    lines.append("CREATE INDEX IF NOT EXISTS idx_curated_apps_record_hash    ON curated_apps (record_hash);")
    lines.append("CREATE INDEX IF NOT EXISTS idx_curated_apps_conflict       ON curated_apps (flag_conflicting_label);")
    lines.append("")
    lines.append("-- Pipeline run audit trail.")
    lines.append("CREATE TABLE IF NOT EXISTS pipeline_runs (")
    lines.append("    run_id            TEXT PRIMARY KEY,")
    lines.append("    stage             TEXT NOT NULL,")
    lines.append("    started_at_utc    TIMESTAMPTZ NOT NULL DEFAULT now(),")
    lines.append("    finished_at_utc   TIMESTAMPTZ,")
    lines.append("    status            TEXT NOT NULL DEFAULT 'running',")
    lines.append("    rows_in           BIGINT,")
    lines.append("    rows_out          BIGINT,")
    lines.append("    notes             TEXT")
    lines.append(");")
    lines.append("")
    lines.append("-- Metric snapshots per evaluation run.")
    lines.append("CREATE TABLE IF NOT EXISTS model_metrics (")
    lines.append("    evaluate_run_id   TEXT NOT NULL,")
    lines.append("    model             TEXT NOT NULL,")
    lines.append("    metric            TEXT NOT NULL,")
    lines.append("    value             DOUBLE PRECISION NOT NULL,")
    lines.append("    loaded_at_utc     TIMESTAMPTZ NOT NULL DEFAULT now(),")
    lines.append("    PRIMARY KEY (evaluate_run_id, model, metric)")
    lines.append(");")
    lines.append("")
    lines.append("-- Partial partition example: rows flagged as conflicting labels.")
    lines.append("CREATE TABLE IF NOT EXISTS curated_apps_conflicting (")
    lines.append("    LIKE curated_apps INCLUDING ALL")
    lines.append(");")
    lines.append("")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT}")
    print(f"  feature columns: {len(feature_cols)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())